#!/usr/bin/env python3
"""Generate PAL_Master.png from palette.json (pure Python, no PIL).

RGB = albedo, A = 1 - emission. Unused cells are filled with debug magenta so mis-mapped UVs are obvious.
Also writes palette_index.md (swatch name -> row/col/uv) for humans.
"""
import json, os, struct, sys, zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAL_DIR = os.path.join(ROOT, "Assets", "Art", "Textures", "Palette")


def hex_rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def write_png(path, w, h, rows_rgba):
    raw = b"".join(b"\x00" + bytes(r) for r in rows_rgba)
    def chunk(tag, data):
        c = struct.pack(">I", len(data)) + tag + data
        return c + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
    png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
    with open(path, "wb") as f:
        f.write(png)


def main():
    pal = json.load(open(os.path.join(PAL_DIR, "palette.json")))
    size, cell = pal["size"], pal["cell"]
    grid = size // cell
    px = [[(255, 0, 255, 255)] * size for _ in range(size)]  # [y][x], y=0 is TOP row of the image
    index, names = [], set()
    for r, row in enumerate(pal["rows"]):
        if r >= grid or len(row["swatches"]) > grid:
            sys.exit(f"palette overflow in row {r} ({row['family']})")
        for c, sw in enumerate(row["swatches"]):
            name, col = sw[0], hex_rgb(sw[1])
            emission = float(sw[2]) if len(sw) > 2 else 0.0
            if name in names:
                sys.exit(f"duplicate swatch name {name}")
            names.add(name)
            a = round(255 * (1.0 - emission))
            for y in range(r * cell, (r + 1) * cell):
                for x in range(c * cell, (c + 1) * cell):
                    px[y][x] = (*col, a)
            u = (c + 0.5) / grid
            v = 1.0 - (r + 0.5) / grid  # UV origin bottom-left
            index.append((name, row["family"], r, c, u, v, sw[1], emission))
    rows = [[ch for p in line for ch in p] for line in px]
    write_png(os.path.join(PAL_DIR, "PAL_Master.png"), size, size, rows)
    with open(os.path.join(PAL_DIR, "palette_index.md"), "w") as f:
        f.write("# Palette index (generated by Tools/build_palette.py — do not edit)\n\n")
        f.write("| swatch | family | row | col | u | v | hex | emission |\n|---|---|---|---|---|---|---|---|\n")
        for n, fam, r, c, u, v, hx, e in index:
            f.write(f"| {n} | {fam} | {r} | {c} | {u:.5f} | {v:.5f} | {hx} | {e} |\n")
    print(f"PAL_Master.png {size}x{size}, {len(index)} swatches")


if __name__ == "__main__":
    main()
